'''
Peça ao usuário para digitar uma palavra. Use fatiamento 
com passo negativo para inverter a palavra e exibi-la. 
Por exemplo, "python" se tornaria "nohtyp".

O que praticar:
Fatiamento com passo ([::-1]).
'''

palavra = input('Digite uma palavra: ')

print('Palavra invertida:', palavra[::-1])  