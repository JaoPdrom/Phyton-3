'''
Peça ao usuário para digitar seu nome completo. Exiba o nome com:

1. Todas as letras em maiúsculas.
2. Todas as letras em minúsculas.
3. Apenas a primeira letra em maiúscula (capitalizada).

O que praticar:
Métodos .upper(), .lower() e .capitalize().
'''

nome = input('Digite seu nome completo: ')

print('Nome em maiusculas:', nome.upper())
print('Nome em minusculas:', nome.lower())
print('Nome capitalizado:', nome.capitalize())