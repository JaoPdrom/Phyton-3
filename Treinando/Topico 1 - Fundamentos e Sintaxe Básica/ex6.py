'''
Peça ao usuário para inserir três notas (podem ser números com casas decimais, como 7.5). 
Calcule a média dessas três notas e exiba o resultado.

O que praticar:
input(), conversão de tipo com float() e cálculo de média.
'''

nota1 = float(input('Informe a nota 1: '))
nota2 = float(input('Informe a nota 2: '))
nota3 = float(input('Informe a nota 3: '))

print((nota1+nota2+nota3)/3)