#for + Range
#range(start, stop, step)

numeros1 = range(10) #vai de o a 10
print(numeros1)
for valor1 in numeros1:
    print(valor1) 

numeros2 = range(5, 10) #vai de 5 a 10
print(numeros2)
for valor2 in numeros2:
    print(valor2)

numeros3 = range(5, 10, 2) #inicia em 5 e vai ate 10 de 2 numeros em 2 numeros
print(numeros3)
for valor3 in numeros3:
    print(valor3)